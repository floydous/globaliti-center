import { test, expect } from '@playwright/test'
import { useLocalAssistant } from './helpers/groqKey.js'

for (const [width, height] of [[320,568],[390,844],[768,1024],[1024,768],[1440,900]]) {
  test(`assistant full cycle ${width}x${height}`, async ({ page }) => {
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height })
    // Isolated browser context; force local fallback without using a real credential.
    await useLocalAssistant(page)
    await page.goto('http://127.0.0.1:4173')
    await expect(page.locator('.sidebar')).not.toContainText('Asisten AI')
    const launcher = page.getByRole('button', { name: 'Buka asisten Globaliti', exact: true })
    await launcher.click()
    const input = page.getByRole('textbox', { name: 'Pesan untuk asisten' })
    await expect(input).toBeFocused()
    await expect(page.getByRole('button', { name: 'Kirim', exact: true })).toBeDisabled()
    await input.fill('Tambah stok Matcha Cup 2')
    await input.press('Enter')
    await page.getByRole('button', { name: 'Terapkan Perubahan', exact: true }).click()
    await expect(page.getByRole('log')).toContainText('Telah Diterapkan')
    await input.press('Escape')
    await expect(page.getByRole('dialog', { name: 'Asisten Globaliti' })).toBeHidden()
    await expect(launcher).toBeFocused()
    await expect(page.getByRole('button', { name: '26 Matcha Cup Rp 8.000', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Katalog & Stok', exact: true }).click()
    await launcher.click()
    await expect(page.getByRole('log')).toContainText('Telah Diterapkan')
    await input.fill('Tambah stok Matcha Cup 3')
    await input.press('Enter')
    await page.getByRole('button', { name: 'Batalkan', exact: true }).click()
    await expect(page.getByRole('log')).toContainText('Dibatalkan')
    const box = await page.getByRole('dialog', { name: 'Asisten Globaliti' }).boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(width)
    expect(box.y + box.height).toBeLessThanOrEqual(height)
    const list = page.getByRole('log')
    expect(await list.evaluate(e => e.scrollHeight - e.scrollTop - e.clientHeight)).toBeLessThan(3)
    await page.screenshot({ path: `dogfood-output/screenshots/chat-${width}.png` })
    await page.getByRole('button', { name: 'Tutup asisten', exact: true }).click()
    await page.getByRole('button', { name: 'Kasir POS', exact: true }).click()
    await expect(page.getByRole('button', { name: '26 Matcha Cup Rp 8.000', exact: true })).toBeVisible()
    expect(errors).toEqual([])
  })
}
