import { test, expect } from '@playwright/test'

test('completed unpaid print keeps receivable until actual payment', async ({ page }) => {
  await page.goto('http://127.0.0.1:4173')
  const nav = name => page.getByRole('button', { name, exact: true }).click()
  const amount = async label => Number((await page.locator('.statement-row').filter({ hasText: label }).locator('strong, span').last().innerText()).replace(/[^\d]/g, ''))
  await nav('Laporan Keuangan')
  await page.getByRole('tab', { name: 'Posisi Keuangan (Neraca)' }).click()
  const cash = await amount('Kas dan Setara Kas')
  const receivable = await amount('Piutang Jasa Print')
  await nav('Jasa Print Word')
  const row = page.locator('.print-order-row').filter({ hasText: 'Lampiran_Tugas.docx' })
  await row.getByRole('button', { name: 'Selesai', exact: true }).click()
  await nav('Laporan Keuangan')
  await page.getByRole('tab', { name: 'Posisi Keuangan (Neraca)' }).click()
  expect(await amount('Piutang Jasa Print')).toBe(receivable)
  expect(await amount('Kas dan Setara Kas')).toBe(cash)
  await nav('Jasa Print Word')
  await row.getByRole('button', { name: 'Tandai lunas', exact: true }).click()
  await nav('Laporan Keuangan')
  await page.getByRole('tab', { name: 'Posisi Keuangan (Neraca)' }).click()
  expect(await amount('Piutang Jasa Print')).toBe(receivable - 2000)
  expect(await amount('Kas dan Setara Kas')).toBe(cash + 2000)
})
